def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    candidates = [
        Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts" / ("consolab.ttf" if bold else "consola.ttf"),
        Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts" / ("arialbd.ttf" if bold else "arial.ttf"),
    ]
    for candidate in candidates:
        if candidate.exists():
            return ImageFont.truetype(str(candidate), size)
    return ImageFont.load_default()


def make_jpeg(name: str, item: dict, columns: list[str], rows: list[tuple]) -> None:
    """Render executed rows as a clean, self-contained SQL-output screenshot."""
    width, margin, row_height = 1800, 55, 29
    header_height = 130
    question_lines = textwrap.wrap(item["question"], width=145)
    question_height = max(92, 28 + len(question_lines) * 25)
    height = header_height + question_height + (len(rows) + 1) * row_height + 85
    image = Image.new("RGB", (width, height), "#F8FAFC")
    draw = ImageDraw.Draw(image)
    title_font, body_font, mono_font = font(30, True), font(17), font(16)
    draw.rectangle((0, 0, width, header_height), fill="#172B4D")
    draw.text((margin, 26), "DATA VORTEX 2026 | ROUND 1 - PHASE 2", fill="white", font=title_font)
    draw.text((margin, 78), f"EXECUTED SQL OUTPUT - {item['difficulty'].upper()} | {item['id']}", fill="#BFDBFE", font=body_font)
    for line_number, line in enumerate(question_lines):
        draw.text(
            (margin, header_height + 15 + line_number * 25), line,
            fill="#172B4D", font=body_font,
        )
    table_top = header_height + question_height
    available = width - (margin * 2)
    col_width = available // len(columns)
    draw.rectangle((margin, table_top, width - margin, table_top + row_height), fill="#1D4ED8")
    for index, column in enumerate(columns):
        draw.text((margin + index * col_width + 6, table_top + 6), column, fill="white", font=mono_font)
    for row_index, row in enumerate(rows):
        y = table_top + row_height * (row_index + 1)
        if row_index % 2 == 0:
            draw.rectangle((margin, y, width - margin, y + row_height), fill="#EAF2FF")
        for column_index, value in enumerate(row):
            value_text = f"{value:,}" if isinstance(value, int) else str(value)
            draw.text((margin + column_index * col_width + 6, y + 6), value_text, fill="#0F172A", font=mono_font)
    footer = "Source: data/data_vortex.db (read-only) | SQL query executed successfully"
    draw.text((margin, height - 45), footer, fill="#475569", font=body_font)
    image.save(SUBMISSION_DIR / name, "JPEG", quality=92, optimize=True)


