SUBMISSION_DIR = PROJECT_ROOT / "submission"

QUESTIONS = {
    "easy": {
        "id": "E2 - Most Engaged Posts",
        "difficulty": "Easy",
        "question": (
            "Find the top 10 posts based on total engagement. Total engagement is "
            "defined as likes + shares + comments. Ignore posts where likes are missing."
        ),
        "sql": """SELECT
    p.post_id,
    p.user_id,
    p.platform,
    p.likes,
    p.shares,
    p.comments,
    p.likes + p.shares + p.comments AS total_engagement
FROM posts AS p
WHERE p.likes IS NOT NULL
ORDER BY total_engagement DESC, p.post_id ASC
LIMIT 10;""",
    },
    "medium": {
        "id": "M1 - Which Locations Generate the Most Engagement?",
        "difficulty": "Medium",
        "question": (
            "Using both datasets, calculate the total engagement generated by users from "
            "each location. Return the location, number of posts, and total engagement. "
            "Rank locations from highest to lowest engagement."
        ),
        "sql": """SELECT
    u.location,
    COUNT(p.post_id) AS post_count,
    SUM(p.likes + p.shares + p.comments) AS total_engagement
FROM users AS u
JOIN posts AS p
    ON p.user_id = u.user_id
WHERE p.likes IS NOT NULL
GROUP BY u.location
ORDER BY total_engagement DESC, u.location ASC;""",
    },
    "hard": {
        "id": "H2 - Rank Users Within Their Location",
        "difficulty": "Hard",
        "question": (
            "For every location, rank users based on their total engagement. Return only "
            "the top 3 users from each location."
        ),
        "sql": """WITH user_engagement AS (
    SELECT
        u.user_id,
        u.location,
        u.follower_count,
        COUNT(p.post_id) AS post_count,
        SUM(p.likes + p.shares + p.comments) AS total_engagement
    FROM users AS u
    JOIN posts AS p
        ON p.user_id = u.user_id
    WHERE p.likes IS NOT NULL
    GROUP BY u.user_id, u.location, u.follower_count
), ranked_users AS (
    SELECT
        user_id,
        location,
        follower_count,
        post_count,
        total_engagement,
        DENSE_RANK() OVER (
            PARTITION BY location
            ORDER BY total_engagement DESC
        ) AS engagement_rank
    FROM user_engagement
)
SELECT
    location,
    engagement_rank,
    user_id,
    follower_count,
    post_count,
    total_engagement
FROM ranked_users
WHERE engagement_rank <= 3
ORDER BY location ASC, engagement_rank ASC, user_id ASC;""",
    },
}


def read_only_connection() -> sqlite3.Connection:
    """Open the project database in SQLite read-only mode."""
    uri = f"file:{DATABASE_PATH.as_posix()}?mode=ro"
    return sqlite3.connect(uri, uri=True)


def execute_query(conn: sqlite3.Connection, sql: str) -> tuple[list[str], list[tuple]]:
    cursor = conn.execute(sql)
    columns = [item[0] for item in cursor.description]
    return columns, cursor.fetchall()


def validate_results(conn: sqlite3.Connection, results: dict[str, tuple[list[str], list[tuple]]]) -> None:
    """Reconcile output totals and rankings without modifying the source DB."""
    easy_columns, easy_rows = results["easy"]
    medium_columns, medium_rows = results["medium"]
    hard_columns, hard_rows = results["hard"]

    assert len(easy_rows) == 10 and easy_columns[-1] == "total_engagement"
    assert all(row[3] is not None for row in easy_rows)
    assert all(
        easy_rows[index][-1] >= easy_rows[index + 1][-1]
        for index in range(len(easy_rows) - 1)
    )

    posts_with_likes, direct_total = conn.execute(
        """SELECT COUNT(*), SUM(likes + shares + comments)
           FROM posts WHERE likes IS NOT NULL"""
    ).fetchone()
    assert sum(row[1] for row in medium_rows) == posts_with_likes
    assert sum(row[2] for row in medium_rows) == direct_total
    assert medium_columns == ["location", "post_count", "total_engagement"]

    expected_hard_rows = conn.execute(
        """SELECT SUM(CASE WHEN user_count >= 3 THEN 3 ELSE user_count END)
           FROM (
               SELECT u.location, COUNT(DISTINCT p.user_id) AS user_count
               FROM users AS u
               JOIN posts AS p ON p.user_id = u.user_id
               WHERE p.likes IS NOT NULL
               GROUP BY u.location
           )"""
    ).fetchone()[0]
    assert len(hard_rows) == expected_hard_rows
    assert all(1 <= row[1] <= 3 for row in hard_rows)
    assert hard_columns == [
        "location",
        "engagement_rank",
        "user_id",
        "follower_count",
        "post_count",
        "total_engagement",
    ]


def styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "Title", parent=base["Title"], alignment=TA_CENTER, fontSize=22,
            leading=28, textColor=colors.HexColor("#172B4D"), spaceAfter=16,
        ),
        "subtitle": ParagraphStyle(
            "Subtitle", parent=base["Normal"], alignment=TA_CENTER, fontSize=11,
            leading=15, textColor=colors.HexColor("#4A5568"), spaceAfter=20,
        ),
        "h1": ParagraphStyle(
            "H1", parent=base["Heading1"], fontSize=16, leading=20,
            textColor=colors.HexColor("#172B4D"), spaceBefore=8, spaceAfter=8,
        ),
        "h2": ParagraphStyle(
            "H2", parent=base["Heading2"], fontSize=12, leading=16,
            textColor=colors.HexColor("#1D4ED8"), spaceBefore=8, spaceAfter=5,
        ),
        "body": ParagraphStyle(
            "Body", parent=base["BodyText"], fontSize=9.3, leading=13,
            spaceAfter=6,
        ),
        "small": ParagraphStyle(
            "Small", parent=base["BodyText"], fontSize=7.6, leading=10,
        ),
        "code": ParagraphStyle(
            "Code", fontName="Courier", fontSize=6.6, leading=8.2,
        ),
    }


def page_number(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#64748B"))
    canvas.drawString(0.55 * inch, 0.35 * inch, "Data Vortex 2026 | Round 1 Phase 2")
    canvas.drawRightString(A4[0] - 0.55 * inch, 0.35 * inch, f"Page {doc.page}")
    canvas.restoreState()


def paragraph(text: str, style: ParagraphStyle) -> Paragraph:
    return Paragraph(text.replace("&", "&amp;"), style)


def results_table(columns: Sequence[str], rows: Sequence[Sequence], width: float) -> LongTable:
    formatted = [list(columns)]
    for row in rows:
        formatted.append([
            f"{value:,}" if isinstance(value, int) else ("" if value is None else str(value))
            for value in row
        ])
    col_width = width / len(columns)
    table = LongTable(formatted, repeatRows=1, colWidths=[col_width] * len(columns))
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#172B4D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 6.7),
        ("LEADING", (0, 0), (-1, -1), 8.2),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#CBD5E1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return table


def build_pdf(path: Path, story: list) -> None:
    doc = SimpleDocTemplate(
        str(path), pagesize=A4, rightMargin=0.55 * inch, leftMargin=0.55 * inch,
        topMargin=0.55 * inch, bottomMargin=0.6 * inch,
        title=path.stem.replace("_", " "), author="Data Vortex 2026",
    )
    doc.build(story, onFirstPage=page_number, onLaterPages=page_number)


def cover(title: str, subtitle: str, style: dict[str, ParagraphStyle]) -> list:
    return [
        Spacer(1, 1.65 * inch),
        Paragraph("DATA VORTEX 2026", style["title"]),
        Paragraph("ROUND 1 - PHASE 2", style["title"]),
        Paragraph(title, style["title"]),
        Spacer(1, 0.2 * inch),
        Paragraph(subtitle, style["subtitle"]),
        Paragraph("Prepared from the project SQLite database using read-only SELECT analysis.", style["subtitle"]),
        PageBreak(),
    ]


def make_sql_pdf(results: dict[str, tuple[list[str], list[tuple]]]) -> None:
    style = styles()
    story = cover("FINAL SQL QUERIES", "One selected question at each required difficulty", style)
    for key in ("easy", "medium", "hard"):
        item = QUESTIONS[key]
        story.extend([
            Paragraph(f"{item['difficulty'].upper()} QUESTION - {item['id']}", style["h1"]),
            paragraph(f"<b>Official question:</b> {item['question']}", style["body"]),
            Spacer(1, 5),
            Preformatted(item["sql"], style["code"]),
            Spacer(1, 8),
            paragraph(
                f"Executed successfully against <b>data/data_vortex.db</b>. "
                f"Returned {len(results[key][1]):,} row(s).",
                style["small"],
            ),
            PageBreak() if key != "hard" else Spacer(1, 1),
        ])
    build_pdf(SUBMISSION_DIR / "Data_Vortex_Phase2_SQL_Queries.pdf", story)


def make_logic_pdf(results: dict[str, tuple[list[str], list[tuple]]]) -> None:
    style = styles()
    story = cover("LOGIC EXPLANATION", "Analytical reasoning, validation, and assumptions", style)
    narratives = {
        "easy": [
            ("Analytical objective", "Identify the ten complete-engagement posts with the highest combined interactions."),
            ("Data and filtering", "The posts table supplies the post ID, platform, and interaction columns. The official instruction requires missing likes to be ignored, so WHERE likes IS NOT NULL is applied before ranking."),
            ("Calculation and ordering", "Total engagement is calculated row by row as likes + shares + comments. Ordering descending returns the largest totals; post_id is a deterministic tie-breaker."),
            ("Validation and edge cases", "The query returned exactly 10 rows, all with non-null likes. No joins are used, so there is no risk of duplicate multiplication."),
        ],
        "medium": [
            ("Analytical objective", "Measure the total complete engagement associated with creators at each location."),
            ("Tables and join", "users provides location and posts provides engagement. The one-to-many join uses posts.user_id = users.user_id, the database foreign-key relationship."),
            ("Filtering and aggregation", "Posts with missing likes are excluded because a complete likes + shares + comments total cannot be calculated. GROUP BY location then produces the requested post count and total engagement."),
            ("Validation and edge cases", "Grouped post counts reconcile to the number of posts with non-null likes, and grouped engagement totals reconcile exactly to a direct database-wide total. Every retained post has one matching user."),
        ],
        "hard": [
            ("Analytical objective", "Rank creators within their own locations, then retain the leading three positions per location."),
            ("Transformation", "The first CTE creates one row per user after joining users to posts and aggregating complete engagement. This prevents a creator with many posts from appearing multiple times in the ranking stage."),
            ("Window ranking", "DENSE_RANK partitions by location and orders total engagement descending. The final filter retains engagement_rank <= 3, preserving any genuine ties at a top-three rank."),
            ("Validation and edge cases", "All output ranks are between 1 and 3. The returned row count reconciles to the sum of the first three available ranking positions across locations; the read-only analysis avoids source-database mutation."),
        ],
    }
    for key in ("easy", "medium", "hard"):
        item = QUESTIONS[key]
        story.append(Paragraph(f"{item['difficulty'].upper()} - {item['id']}", style["h1"]))
        story.append(paragraph(f"<b>Official question:</b> {item['question']}", style["body"]))
        for heading, text in narratives[key]:
            story.append(Paragraph(heading, style["h2"]))
            story.append(paragraph(text, style["body"]))
        story.append(paragraph(f"Executed result: <b>{len(results[key][1]):,} row(s)</b> returned.", style["body"]))
        if key != "hard":
            story.append(PageBreak())
    build_pdf(SUBMISSION_DIR / "Data_Vortex_Phase2_Logic_Explanation.pdf", story)


