def validate_artifacts() -> None:
    required = [
        "Data_Vortex_Phase2_SQL_Queries.pdf",
        "Data_Vortex_Phase2_Logic_Explanation.pdf",
        "Data_Vortex_Phase2_Insight_Report.pdf",
        "Easy_Output.jpeg",
        "Medium_Output.jpeg",
        "Hard_Output.jpeg",
        "SUBMISSION_MANIFEST.txt",
    ]
    for filename in required:
        path = SUBMISSION_DIR / filename
        assert path.exists() and path.stat().st_size > 0, f"Missing artifact: {filename}"
        assert path.stat().st_size < 10 * 1024 * 1024, f"Artifact exceeds 10 MB: {filename}"
    for filename in ("Easy_Output.jpeg", "Medium_Output.jpeg", "Hard_Output.jpeg"):
        with Image.open(SUBMISSION_DIR / filename) as image:
            assert image.format == "JPEG", f"Invalid image format: {filename}"
            image.verify()
    for filename in required[:3]:
        assert (SUBMISSION_DIR / filename).read_bytes()[:4] == b"%PDF", f"Invalid PDF: {filename}"


def main() -> None:
    SUBMISSION_DIR.mkdir(exist_ok=True)
    with read_only_connection() as conn:
        integrity = conn.execute("PRAGMA integrity_check").fetchone()[0]
        foreign_keys = conn.execute("PRAGMA foreign_key_check").fetchall()
        assert integrity == "ok" and not foreign_keys, "Database integrity validation failed"
        results = {key: execute_query(conn, item["sql"]) for key, item in QUESTIONS.items()}
        validate_results(conn, results)
    make_sql_pdf(results)
    make_logic_pdf(results)
    make_insight_pdf(results)
    make_jpeg("Easy_Output.jpeg", QUESTIONS["easy"], *results["easy"])
    make_jpeg("Medium_Output.jpeg", QUESTIONS["medium"], *results["medium"])
    make_jpeg("Hard_Output.jpeg", QUESTIONS["hard"], *results["hard"])
    write_manifest()
    validate_artifacts()
    print(f"Submission package created and validated: {SUBMISSION_DIR}")


if __name__ == "__main__":
    main()
